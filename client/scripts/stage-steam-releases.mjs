import fs from "node:fs";
import path from "node:path";
import { clientDir, installFolder, launchOptions, platforms, releaseRoot } from "./release-config.mjs";

function copyDirectoryContents(sourceDir, destinationDir) {
  fs.mkdirSync(destinationDir, { recursive: true });
  for (const entry of fs.readdirSync(sourceDir)) {
    fs.cpSync(path.join(sourceDir, entry), path.join(destinationDir, entry), {
      recursive: true,
      dereference: false,
      verbatimSymlinks: true,
    });
  }
}

function ensureSourceExists(platform) {
  if (!fs.existsSync(platform.sourceDir)) {
    throw new Error(
      `Missing ${platform.label} build output at ${path.relative(clientDir, platform.sourceDir)}. Run npm run dist first.`
    );
  }
}

fs.rmSync(releaseRoot, { recursive: true, force: true });
fs.mkdirSync(releaseRoot, { recursive: true });

for (const platform of platforms) {
  ensureSourceExists(platform);
  copyDirectoryContents(platform.sourceDir, platform.stageDir);
}

const manifest = {
  generatedAt: new Date().toISOString(),
  installFolder,
  platforms: launchOptions.map((platform) => ({
    platform: platform.platform,
    executable: platform.executable,
    depotId: platform.depotId,
    stageDir: path.relative(clientDir, platform.stageDir),
    steamLocalPath: platform.steamLocalPath,
  })),
};

const lines = [
  "# Steam Release Layout",
  "",
  `Install folder: ${installFolder}`,
  "",
  "Platform folders:",
  ...launchOptions.map(
    (platform) =>
      `- ${platform.platform}: ${path.relative(clientDir, platform.stageDir)} -> ${platform.executable} (Depot ${platform.depotId})`
  ),
  "",
  "Steam launch executables:",
  ...launchOptions.map((platform) => `- ${platform.platform}: ${platform.executable}`),
  "",
  "This folder is generated by npm run stage:steam or npm run dist:steam.",
];

fs.writeFileSync(path.join(releaseRoot, "platform-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
fs.writeFileSync(path.join(releaseRoot, "README.md"), `${lines.join("\n")}\n`);

console.log("Steam release folders staged:");
for (const platform of platforms) {
  console.log(`- ${platform.label}: ${path.relative(clientDir, platform.stageDir)}`);
}
